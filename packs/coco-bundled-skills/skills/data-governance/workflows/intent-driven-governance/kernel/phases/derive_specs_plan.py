def _validate_destructive_approval(value: Any, destructive_ids: set[str]) -> list[str]:
    if not isinstance(value, dict):
        return ["phase_details.derive_specs_plan.destructive_change_approval must be a mapping"]
    errors: list[str] = []
    for field in ("approved_by", "approved_at", "approval_text"):
        if not isinstance(value.get(field), str) or not value.get(field, "").strip():
            errors.append(f"phase_details.derive_specs_plan.destructive_change_approval.{field} is required")
    approved_items = value.get("approved_items")
    if not isinstance(approved_items, list):
        errors.append("phase_details.derive_specs_plan.destructive_change_approval.approved_items must be a list")
    else:
        missing = sorted(destructive_ids - {str(item) for item in approved_items})
        if missing:
            errors.append(f"destructive_change_approval does not cover destructive item(s): {missing}")
    return errors


