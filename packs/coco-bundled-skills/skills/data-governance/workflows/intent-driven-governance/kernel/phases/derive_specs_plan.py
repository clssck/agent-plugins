def _validate_approved_intent_mapping(value: Any, state: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    if not isinstance(value, list) or not value:
        return ["phase_details.derive_specs_plan.approved_intent_mapping must be a non-empty list"]
    planned_refs = set()
    for idx, item in enumerate(value):
        if not isinstance(item, dict):
            errors.append(f"phase_details.derive_specs_plan.approved_intent_mapping[{idx}] must be a mapping")
            continue
        for field in ("scope_path", "customer_intent", "target_status", "spec_items"):
            if field not in item:
                errors.append(f"phase_details.derive_specs_plan.approved_intent_mapping[{idx}].{field} is required")
        if isinstance(item.get("scope_path"), str):
            planned_refs.add(item["scope_path"])
        if "spec_items" in item and not isinstance(item["spec_items"], list):
            errors.append(f"phase_details.derive_specs_plan.approved_intent_mapping[{idx}].spec_items must be a list")
    capture = phase_artifact(state, "capture_intent") or {}
    for scope_intent in capture.get("scope_intents", []):
        if not isinstance(scope_intent, dict):
            continue
        scope_path = scope_intent.get("scope_path")
        if isinstance(scope_path, str) and scope_path not in planned_refs:
            errors.append(f"approved scope intent {scope_path!r} is not mapped in approved_intent_mapping")
    return errors


