def _collect_no_change_decisions(artifact: dict[str, Any]) -> list[Any]:
    decisions: list[Any] = []
    delta = artifact.get("implementation_delta", {}) if isinstance(artifact.get("implementation_delta"), dict) else {}
    if isinstance(delta.get("no_op_no_change_decisions"), list):
        decisions.extend(delta["no_op_no_change_decisions"])
