def validate_artifact(state: dict[str, Any]) -> list[str]:
    errors = validate_phase_log_entry(state, 3, "derive_specs_plan")
    artifact = phase_artifact(state, "derive_specs_plan")
    if artifact is None:
        errors.append("missing phase_details.derive_specs_plan")
    else:
        errors.extend(validate_artifact_location(artifact, "derive_specs_plan", 3))
        errors.extend(_validate_governance_spec_artifact(artifact, state))
    if not isinstance(state.get("intent_artifacts"), dict):
        errors.append("intent_artifacts must be present")
    if not has_delta(state):
        errors.append("delta must be present")
    if not state.get("scoped_digest"):
        errors.append("scoped_digest is required")
    return errors


def can_exit_phase(state: dict[str, Any]) -> bool:
    return not validate_artifact(state) and has_user_agreement(state, 3)


