    if not isinstance(value, dict):
        return []
    lines = [f"  - {_text(value.get('name'), 'unnamed subscope')}: {_text(value.get('target_status'), 'unknown')}"]
    for field, label in (
        ("resulting_protected_objects", "protected"),
        ("new_controls_to_apply", "new controls"),
        ("intentionally_unprotected_objects", "intentionally unprotected"),
    ):
        if value.get(field):
            lines.append(f"    - {label}: {_join(value.get(field))}")
    return lines


