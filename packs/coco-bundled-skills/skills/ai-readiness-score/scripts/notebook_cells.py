def code_cache_helpers() -> str:
    return '''\
def _lower(row):
    return {k.lower(): v for k, v in row.items()}

def run_query(c, sql):
    with c.cursor(DictCursor) as cur:
        cur.execute(sql)
        return [_lower(r) for r in cur.fetchall()]

def cache_path(label):
    return f"{CACHE_STAGE}/{label}.parquet"

def cache_exists(c, path):
    try:
        with c.cursor() as cur:
            cur.execute(f"LIST {path}")
            return len(cur.fetchall()) > 0
    except Exception:
        return False

def _ensure_db_context(c):
    """Ensure the session has a database/schema context for temp object creation."""
    try:
        row = c.cursor().execute("SELECT CURRENT_DATABASE(), CURRENT_SCHEMA()").fetchone()
        if row and row[0] and row[1]:
            return True
        if row and row[0] and not row[1]:
            c.cursor().execute("USE SCHEMA PUBLIC")
            return True
    except Exception:
        pass
    try:
        _user = c.cursor().execute("SELECT CURRENT_USER()").fetchone()[0]
        c.cursor().execute(f'USE DATABASE "USER${_user}"')
        c.cursor().execute("USE SCHEMA PUBLIC")
        return True
    except Exception:
        pass
    raise RuntimeError(
        "NO_DATABASE_CONTEXT: No database is set and USER$ database is not available. "
        "Please specify a database and schema to use."
    )

_ensure_db_context(conn)

def write_cache(c, sql, path):
    sql = sql.rstrip().rstrip(";")
    _ensure_db_context(c)
    with c.cursor() as cur:
        cur.execute(f"""COPY INTO {path} FROM ({sql}) FILE_FORMAT = (TYPE = PARQUET) OVERWRITE = TRUE SINGLE = TRUE HEADER = TRUE MAX_FILE_SIZE = 268435456""")

def read_cache(c, path):
    _ensure_db_context(c)
    import traceback
    for attempt in range(2):
        try:
            with c.cursor() as cur:
                cur.execute("CREATE OR REPLACE TEMP FILE FORMAT _ai_readiness_parquet TYPE = PARQUET")
                cur.execute(f"SELECT $1 FROM {path} (FILE_FORMAT => _ai_readiness_parquet)")
                rows = []
                for (v,) in cur.fetchall():
                    obj = json.loads(v) if isinstance(v, str) else (v if isinstance(v, dict) else json.loads(str(v)))
                    rows.append({k.lower(): val for k, val in obj.items()})
                return rows
        except Exception as exc:
            err_msg = str(exc)
            is_transient = any(s in err_msg for s in ["503", "429", "Timeout", "RetryRequest", "Service Unavailable"])
            if attempt == 0 and is_transient:
                print(f"  ⚠️ Cache read hit transient error (retrying in 3s): {type(exc).__name__}: {err_msg[:200]}")
                time.sleep(3)
            else:
                print(f"  ❌ Cache read failed (will re-query from scratch):")
                print(f"     Error type: {type(exc).__name__}")
                print(f"     Message: {err_msg[:300]}")
                traceback.print_exc()
                return []

def write_json_cache(c, data, path):
    escaped = data.replace("\\\\", "\\\\\\\\").replace("'", "''")
    _ensure_db_context(c)
    with c.cursor() as cur:
        cur.execute(f"""COPY INTO {path} FROM (SELECT '{escaped}' AS json_payload) FILE_FORMAT = (TYPE = PARQUET) OVERWRITE = TRUE SINGLE = TRUE HEADER = TRUE MAX_FILE_SIZE = 268435456""")

def read_json_cache(c, path):
    _ensure_db_context(c)
    import traceback
    for attempt in range(2):
        try:
            with c.cursor() as cur:
                cur.execute("CREATE OR REPLACE TEMP FILE FORMAT _ai_readiness_parquet TYPE = PARQUET")
            rows = run_query(c, f"SELECT $1:json_payload::STRING AS json_payload FROM {path} (FILE_FORMAT => _ai_readiness_parquet)")
            return rows[0].get("json_payload") if rows else None
        except Exception as exc:
            err_msg = str(exc)
            is_transient = any(s in err_msg for s in ["503", "429", "Timeout", "RetryRequest", "Service Unavailable"])
            if attempt == 0 and is_transient:
                print(f"  ⚠️ JSON cache read hit transient error (retrying in 3s): {type(exc).__name__}: {err_msg[:200]}")
                time.sleep(3)
            else:
                print(f"  ❌ JSON cache read failed (will re-query from scratch):")
                print(f"     Error type: {type(exc).__name__}")
                print(f"     Message: {err_msg[:300]}")
                traceback.print_exc()
                return None

print("🔧 Cache helpers ready")
'''


