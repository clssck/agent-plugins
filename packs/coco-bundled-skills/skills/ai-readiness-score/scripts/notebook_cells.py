def code_sv_scoring() -> str:
    return r'''
def describe_view_vqr(c, fqn):
    quoted = fqn["quoted"]
    display = fqn["display"]
    last_err = None
    for attempt in range(3):
        try:
            with c.cursor(DictCursor) as cur:
                cur.execute(f"DESCRIBE SEMANTIC VIEW {quoted}", timeout=20)
                rows = [_lower(r) for r in cur.fetchall()]
            vqr_count = 0
            for row in rows:
                kind = (row.get("object_kind") or "").upper()
                if kind in ("AI_VERIFIED_QUERY", "VERIFIED_QUERY"):
                    vqr_count += 1
                elif kind == "EXTENSION" and (row.get("object_name") or "").upper() == "CA" and (row.get("property") or "").upper() == "VALUE":
                    try:
                        ext = json.loads(row.get("property_value", "{}"))
                        vqr_count += len(ext.get("verified_queries", []))
                        vqr_count += len(ext.get("ai_verified_queries", []))
                    except Exception:
                        pass
            return {"fqn": display, "vqr_count": vqr_count}
        except Exception as e:
            last_err = e
    return {"fqn": display, "vqr_count": None, "error": str(last_err)}


def run_sv_step():
    global sv_results, vqr_data
    t_total = time.perf_counter()
    c = session.connection

    vqr_cache_p = cache_path(f"vqr_counts{sample_suffix}")
    t0 = time.perf_counter()
    if USE_CACHE and cache_exists(c, vqr_cache_p):
        print("  [SV] Reading VQR counts from cache...")
        cached_json = read_json_cache(c, vqr_cache_p)
        vqr_data = json.loads(cached_json) if cached_json else {}
    else:
        if SAMPLE_PCT:
            filter_clause = f"""WHERE sv.deleted IS NULL
            AND EXISTS (
                SELECT 1 FROM SNOWFLAKE.ACCOUNT_USAGE.SEMANTIC_TABLES st
                WHERE st.SEMANTIC_VIEW_ID = sv.SEMANTIC_VIEW_ID
                  AND st.DELETED IS NULL
                  AND (UPPER(st.BASE_TABLE_DATABASE_NAME), UPPER(st.BASE_TABLE_SCHEMA_NAME), UPPER(st.BASE_TABLE_NAME))
                      IN (SELECT DISTINCT
                              UPPER(SPLIT_PART(f.value:objectName::string, '.', 1)),
                              UPPER(SPLIT_PART(f.value:objectName::string, '.', 2)),
                              UPPER(SPLIT_PART(f.value:objectName::string, '.', 3))
                          FROM snowflake.account_usage.access_history ah,
                               LATERAL FLATTEN(input => ah.base_objects_accessed) f
                          WHERE ah.query_start_time::DATE BETWEEN '{start_ts}'::DATE AND '{end_ts}'::DATE
                            AND ARRAY_SIZE(ah.objects_modified) = 0
                            AND f.value:objectDomain::string = 'Table'
                            AND SPLIT_PART(f.value:objectName::string, '.', 2) != ''
                            AND SPLIT_PART(f.value:objectName::string, '.', 3) != ''
                            AND MOD(ABS(HASH(ah.query_id) % 100), 100) < {SAMPLE_PCT})
            )"""
        else:
            filter_clause = "WHERE sv.deleted IS NULL"

        scan_label_vqr = f"{SAMPLE_PCT}% sample filter" if SAMPLE_PCT else "full scan"
        print(f"  [SV] Extracting VQR counts ({scan_label_vqr})...")

        try:
            # Strategy: try SHOW SEMANTIC VIEWS IN ACCOUNT first (one fast call,
            # account-wide). It caps at 10,000 rows. If we hit that ceiling, the
            # result is potentially truncated, so fall back to per-database
            # INFORMATION_SCHEMA.SEMANTIC_VIEWS (10K cap applies per DB).
            #
            # Each row carries both a display FQN (db.schema.name, for logs/
            # results/cache) and a quoted FQN ("db"."schema"."name", safe to
            # embed in DESCRIBE SEMANTIC VIEW even when names contain non-ASCII
            # characters, spaces, lowercase letters, or reserved words).
            SHOW_LIMIT = 10000
            quoted_fqn_expr_show = (
                "'\"' || REPLACE(\"database_name\", '\"', '\"\"') || '\".\"' || "
                "REPLACE(\"schema_name\",   '\"', '\"\"') || '\".\"' || "
                "REPLACE(\"name\",          '\"', '\"\"') || '\"'"
            )
            display_fqn_expr_show = (
                "\"database_name\" || '.' || \"schema_name\" || '.' || \"name\""
            )
            with c.cursor(DictCursor) as cur:
                cur.execute("SHOW SEMANTIC VIEWS IN ACCOUNT")
                cur.execute(
                    f"SELECT {display_fqn_expr_show} AS display_fqn, "
                    f"{quoted_fqn_expr_show} AS quoted_fqn "
                    "FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) ORDER BY display_fqn"
                )
                show_rows = [_lower(r) for r in cur.fetchall()]

            if len(show_rows) < SHOW_LIMIT:
                seen = set()
                fqns = []
                for row in show_rows:
                    d = row["display_fqn"]
                    if d in seen:
                        continue
                    seen.add(d)
                    fqns.append({"display": d, "quoted": row["quoted_fqn"]})
                print(f"  [SV] Listed {len(fqns):,} semantic views via SHOW")
            else:
                print(
                    f"  [SV] SHOW returned {len(show_rows):,} rows (>= {SHOW_LIMIT:,}); "
                    "result may be truncated — falling back to INFORMATION_SCHEMA per database"
                )
                with c.cursor(DictCursor) as cur:
                    cur.execute("SHOW DATABASES")
                    cur.execute(
                        'SELECT "name" AS db_name FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))'
                    )
                    db_names = [row["db_name"] for row in cur.fetchall()]

                quoted_fqn_expr_info = (
                    "'\"' || REPLACE(\"CATALOG\", '\"', '\"\"') || '\".\"' || "
                    "REPLACE(\"SCHEMA\",  '\"', '\"\"') || '\".\"' || "
                    "REPLACE(\"NAME\",    '\"', '\"\"') || '\"'"
                )
                display_fqn_expr_info = (
                    "\"CATALOG\" || '.' || \"SCHEMA\" || '.' || \"NAME\""
                )
                seen = set()
                fqns = []
                for db in db_names:
                    safe_db = db.replace('"', '""')
                    try:
                        rows = run_query(
                            c,
                            f"SELECT {display_fqn_expr_info} AS display_fqn, "
                            f"{quoted_fqn_expr_info} AS quoted_fqn "
                            f'FROM "{safe_db}".INFORMATION_SCHEMA.SEMANTIC_VIEWS',
                        )
                        if len(rows) >= SHOW_LIMIT:
                            print(
                                f"  [SV] WARNING: {db} returned {len(rows):,} rows "
                                f"(>= {SHOW_LIMIT:,}); INFORMATION_SCHEMA may also be truncated"
                            )
                        for row in rows:
                            d = row["display_fqn"]
                            if d in seen:
                                continue
                            seen.add(d)
                            fqns.append({"display": d, "quoted": row["quoted_fqn"]})
                    except Exception as exc:
                        # Shares / imported DBs / DBs without USAGE often fail here — skip.
                        print(f"  [SV] Skipping {db}: {exc}")

                fqns.sort(key=lambda x: x["display"])
            print(f"  [SV] Found {len(fqns):,} semantic views to scan")

            results = []
            errors = []
            if fqns:
                executor = ThreadPoolExecutor(max_workers=8)
                try:
                    futures = {executor.submit(describe_view_vqr, c, fqn): fqn["display"] for fqn in fqns}
                    for future in tqdm(as_completed(futures), total=len(fqns), desc="  [SV] Describing views"):
                        try:
                            result = future.result()
                            if "error" in result:
                                errors.append({"fqn": result["fqn"], "error": result["error"]})
                            results.append(result)
                        except Exception as e:
                            errors.append({"fqn": futures[future], "error": str(e)})
                except KeyboardInterrupt:
                    print("  [SV] Interrupted — cancelling queued tasks")
                    executor.shutdown(wait=False, cancel_futures=True)
                    raise
                else:
                    executor.shutdown(wait=True)

            vqr_data = {
                "total_views_scanned": len(results),
                "total_vqrs": sum(r["vqr_count"] for r in results if r["vqr_count"] is not None),
                "views_with_vqrs": sum(1 for r in results if r.get("vqr_count") and r["vqr_count"] > 0),
                "errors": len(errors),
                "results": results,
            }
            print(f"  [SV] Scanned {len(results):,} views, {vqr_data['total_vqrs']:,} total VQRs, {len(errors)} errors")

            try:
                write_json_cache(c, json.dumps(vqr_data), vqr_cache_p)
            except Exception as exc:
                print(f"  [SV] VQR cache write failed (non-fatal): {exc}")
        except Exception as exc:
            print(f"  [SV] VQR extraction failed (non-fatal): {exc}")
            vqr_data = {}

    t_vqr = time.perf_counter() - t0
    print(f"  [SV] VQR step [{t_vqr:.1f}s]")

    vqr_map = {}
    for item in vqr_data.get("results", []):
        fqn = item.get("fqn", "")
        count = item.get("vqr_count")
        if fqn and count is not None:
            vqr_map[fqn] = int(count)

    sv_cache_p = cache_path(f"sv_quality{sample_suffix}")
    t0 = time.perf_counter()
    if USE_CACHE and cache_exists(c, sv_cache_p):
        print("  [SV] Reading SV quality from cache...")
        sv_results = read_cache(c, sv_cache_p)
    else:
        print("  [SV] Scoring semantic view quality...")
        if vqr_map:
            vqr_unions = " UNION ALL ".join(
                f"SELECT '{fqn.replace(chr(39), chr(39)+chr(39))}' AS sv_fqn, {count} AS n_verified_queries"
                for fqn, count in vqr_map.items()
            )
            vqr_source = vqr_unions
        else:
            vqr_source = "SELECT NULL AS sv_fqn, NULL AS n_verified_queries WHERE 1=0"
        sv_sql = SQL_SV_QUALITY.format(vqr_source=vqr_source)
        sv_results = run_query(c, sv_sql)
        try:
            write_cache(c, sv_sql, sv_cache_p)
        except Exception as exc:
            print(f"  [SV] Cache write failed (non-fatal): {exc}")

    t_sv = time.perf_counter() - t0
    n_sv = len({str(r.get("sv_fqn") or "") for r in sv_results if r.get("sv_fqn")})
    elapsed = time.perf_counter() - t_total
    execution_times["sv"] = elapsed
    print(f"  [SV] ✅ Found {n_sv:,} semantic views [{elapsed:.1f}s total]")

run_sv_step()
'''


