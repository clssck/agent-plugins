"""Validation for Phase 1: Observe."""

from __future__ import annotations

from typing import Any

from .common import artifact_state_path, has_observed_state, has_user_agreement, phase_artifact, validate_artifact_location, validate_phase_log_entry


_REQUIRED_OBSERVE_SECTIONS = {
    "session": ("account", "region", "role", "role_sufficient"),
    "managed_state": ("status", "location_checked"),
    "scope_observed": ("requested_scope", "objects_observed", "observation_coverage"),
    "observation_boundary": ("excluded_system_databases", "data_freshness"),
    "account_overview": ("visible_non_system_databases", "counts"),
    "live_governance": ("policies", "tags", "classifications", "protected_data"),
    "governance_object_catalog": ("policies", "tags", "classification_profiles", "custom_classifiers"),
}

_REQUIRED_ACCOUNT_COUNTS = (
    "databases",
    "schemas",
    "tables_or_views",
    "roles",
    "data_policies",
    "tags",
    "tag_bindings",
    "classification_profiles",
    "custom_classifiers",
)

_VALID_MANAGED_STATE_STATUSES = {"found", "missing", "unreadable", "handoff_required", "not_writable"}
_VALID_OBSERVATION_COVERAGE = {"complete", "partial_due_to_privilege", "partial_due_to_scope", "intent_only"}
_REQUIRED_OBSERVATION_HEADINGS = (
    "Purpose",
    "Artifact and State Locations",
    "Observation Boundary",
    "Capability / Privilege Check",
    "Account Overview",
    "Governance Scope Inventory",
    "Observed Gaps / Review Areas",
    "Unprotected / Unclassified Scopes",
    "Governance Object Catalog",
    "Limitations and Confidence",
)


_SCOPE_REQUIRED_FIELDS = (
    "scope_id",
    "name",
    "status",
    "objects_in_scope",
    "controls_used",
    "key_gaps",
)


def validate_artifact(state: dict[str, Any]) -> list[str]:
    errors = validate_phase_log_entry(state, 1, "observe")
    artifact = phase_artifact(state, "observe")
    if artifact is None:
        errors.append("missing phase_details.observe")
    else:
        errors.extend(validate_artifact_location(artifact, "observe", 1))
        errors.extend(_validate_observe_artifact(artifact))
    if not has_observed_state(state):
        errors.append("observed_fetched_at is required")
    if not isinstance(state.get("artifacts"), dict):
        errors.append("artifacts must be present")
    return errors


def can_exit_phase(state: dict[str, Any]) -> bool:
    return not validate_artifact(state) and has_user_agreement(state, 1)


