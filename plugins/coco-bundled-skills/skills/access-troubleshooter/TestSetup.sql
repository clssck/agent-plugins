GRANT USAGE ON DATABASE AUTH_TEST_DB TO ROLE TEST_RESTRICTED_READER_ROLE;
GRANT USAGE ON SCHEMA AUTH_TEST_DB.AUTH_TEST_SCHEMA TO ROLE TEST_RESTRICTED_READER_ROLE;
GRANT SELECT ON TABLE AUTH_TEST_DB.AUTH_TEST_SCHEMA.RESTRICTED_DATA TO ROLE TEST_RESTRICTED_READER_ROLE;

-- Role with full DML access (SELECT, INSERT, UPDATE, DELETE) on schema 1
