-- 6a. Databases, schemas, tables -----------------------------------------------

CREATE DATABASE IF NOT EXISTS SRG_SALES_DB;
CREATE SCHEMA IF NOT EXISTS SRG_SALES_DB.ANALYTICS;
CREATE TABLE IF NOT EXISTS SRG_SALES_DB.ANALYTICS.ORDERS (
    id INT,
    amount DECIMAL(10,2),
    region VARCHAR(50)
);

CREATE DATABASE IF NOT EXISTS SRG_FINANCE_DB;
CREATE SCHEMA IF NOT EXISTS SRG_FINANCE_DB.REPORTS;
CREATE TABLE IF NOT EXISTS SRG_FINANCE_DB.REPORTS.BUDGET (
    id INT,
    dept VARCHAR(50),
    total DECIMAL(12,2)
);

-- 6b. Roles (14) ---------------------------------------------------------------

CREATE ROLE IF NOT EXISTS SRG_SALES_IDENTITY;
CREATE ROLE IF NOT EXISTS SRG_SALES_DB_ACCESS;
CREATE ROLE IF NOT EXISTS SRG_SALES_ANALYTICS_ACCESS;
CREATE ROLE IF NOT EXISTS SRG_SALES_READ;
CREATE ROLE IF NOT EXISTS SRG_SALES_WRITE;
CREATE ROLE IF NOT EXISTS SRG_SALES_ADMIN;
CREATE ROLE IF NOT EXISTS SRG_FINANCE_IDENTITY;
CREATE ROLE IF NOT EXISTS SRG_FINANCE_DB_ACCESS;
CREATE ROLE IF NOT EXISTS SRG_FINANCE_REPORTS_ACCESS;
CREATE ROLE IF NOT EXISTS SRG_FINANCE_READ;
CREATE ROLE IF NOT EXISTS SRG_FINANCE_DDL;
CREATE ROLE IF NOT EXISTS SRG_READONLY_IDENTITY;
CREATE ROLE IF NOT EXISTS SRG_PARTIAL_IDENTITY;
CREATE ROLE IF NOT EXISTS SRG_PARTIAL_READ;

-- 6c. Role hierarchy -----------------------------------------------------------
--
-- Sales:  SALES_IDENTITY → SALES_DB_ACCESS → SALES_ANALYTICS_ACCESS
--                                                 ├→ SALES_READ
--                                                 ├→ SALES_WRITE
--                                                 └→ SALES_ADMIN
-- Finance: FINANCE_IDENTITY → FINANCE_DB_ACCESS → FINANCE_REPORTS_ACCESS → FINANCE_READ
-- Cross:   READONLY_IDENTITY → SALES_READ
--          PARTIAL_IDENTITY  → PARTIAL_READ

GRANT ROLE SRG_SALES_DB_ACCESS TO ROLE SRG_SALES_IDENTITY;
GRANT ROLE SRG_SALES_ANALYTICS_ACCESS TO ROLE SRG_SALES_DB_ACCESS;
GRANT ROLE SRG_SALES_READ TO ROLE SRG_SALES_ANALYTICS_ACCESS;
GRANT ROLE SRG_SALES_WRITE TO ROLE SRG_SALES_ANALYTICS_ACCESS;
GRANT ROLE SRG_SALES_ADMIN TO ROLE SRG_SALES_ANALYTICS_ACCESS;

GRANT ROLE SRG_FINANCE_DB_ACCESS TO ROLE SRG_FINANCE_IDENTITY;
GRANT ROLE SRG_FINANCE_REPORTS_ACCESS TO ROLE SRG_FINANCE_DB_ACCESS;
GRANT ROLE SRG_FINANCE_READ TO ROLE SRG_FINANCE_REPORTS_ACCESS;

GRANT ROLE SRG_SALES_READ TO ROLE SRG_READONLY_IDENTITY;
GRANT ROLE SRG_PARTIAL_READ TO ROLE SRG_PARTIAL_IDENTITY;

-- 6d. Privilege grants ----------------------------------------------------------

-- Sales privileges
GRANT USAGE ON DATABASE SRG_SALES_DB TO ROLE SRG_SALES_DB_ACCESS;
GRANT USAGE ON SCHEMA SRG_SALES_DB.ANALYTICS TO ROLE SRG_SALES_ANALYTICS_ACCESS;
GRANT SELECT ON TABLE SRG_SALES_DB.ANALYTICS.ORDERS TO ROLE SRG_SALES_READ;
GRANT INSERT, UPDATE ON TABLE SRG_SALES_DB.ANALYTICS.ORDERS TO ROLE SRG_SALES_WRITE;
GRANT ALL PRIVILEGES ON TABLE SRG_SALES_DB.ANALYTICS.ORDERS TO ROLE SRG_SALES_ADMIN;
-- Leaf roles also get direct DB+schema USAGE so they can function standalone
GRANT USAGE ON DATABASE SRG_SALES_DB TO ROLE SRG_SALES_READ;
GRANT USAGE ON DATABASE SRG_SALES_DB TO ROLE SRG_SALES_WRITE;
GRANT USAGE ON DATABASE SRG_SALES_DB TO ROLE SRG_SALES_ADMIN;
GRANT USAGE ON SCHEMA SRG_SALES_DB.ANALYTICS TO ROLE SRG_SALES_READ;
GRANT USAGE ON SCHEMA SRG_SALES_DB.ANALYTICS TO ROLE SRG_SALES_WRITE;
GRANT USAGE ON SCHEMA SRG_SALES_DB.ANALYTICS TO ROLE SRG_SALES_ADMIN;

-- Finance privileges
GRANT USAGE ON DATABASE SRG_FINANCE_DB TO ROLE SRG_FINANCE_DB_ACCESS;
GRANT USAGE ON SCHEMA SRG_FINANCE_DB.REPORTS TO ROLE SRG_FINANCE_REPORTS_ACCESS;
GRANT SELECT ON TABLE SRG_FINANCE_DB.REPORTS.BUDGET TO ROLE SRG_FINANCE_READ;
GRANT USAGE ON DATABASE SRG_FINANCE_DB TO ROLE SRG_FINANCE_READ;
GRANT USAGE ON SCHEMA SRG_FINANCE_DB.REPORTS TO ROLE SRG_FINANCE_READ;

-- Partial: SELECT on ORDERS only, NO USAGE on DB or schema (IT #5)
GRANT SELECT ON TABLE SRG_SALES_DB.ANALYTICS.ORDERS TO ROLE SRG_PARTIAL_READ;

-- Public gets USAGE on FINANCE_DB (mirrors IT fixture)
GRANT USAGE ON DATABASE SRG_FINANCE_DB TO ROLE PUBLIC;

-- Finance DDL: CREATE TABLE + USAGE on FINANCE_DB.REPORTS
GRANT USAGE ON DATABASE SRG_FINANCE_DB TO ROLE SRG_FINANCE_DDL;
GRANT USAGE ON SCHEMA SRG_FINANCE_DB.REPORTS TO ROLE SRG_FINANCE_DDL;
GRANT CREATE TABLE ON SCHEMA SRG_FINANCE_DB.REPORTS TO ROLE SRG_FINANCE_DDL;

-- 6e. Users (5) ----------------------------------------------------------------
-- U1: Sales (fully authorized for SELECT on ORDERS)
-- U2: Finance (no sales access; has READ on BUDGET, no CREATE TABLE)
-- U3: Readonly (SALES_READ only, via READONLY_IDENTITY)
-- U5: Partial (PARTIAL_READ: SELECT on ORDERS but no USAGE)
-- U6: Finance DDL (can CREATE TABLE in FINANCE_DB.REPORTS)

CREATE USER IF NOT EXISTS SRG_USER_1
    PASSWORD = 'TestPass123!'
    DEFAULT_ROLE = SRG_SALES_IDENTITY;
CREATE USER IF NOT EXISTS SRG_USER_2
    PASSWORD = 'TestPass123!'
    DEFAULT_ROLE = SRG_FINANCE_IDENTITY;
CREATE USER IF NOT EXISTS SRG_USER_3
    PASSWORD = 'TestPass123!'
    DEFAULT_ROLE = SRG_READONLY_IDENTITY;
CREATE USER IF NOT EXISTS SRG_USER_5
    PASSWORD = 'TestPass123!'
    DEFAULT_ROLE = SRG_PARTIAL_IDENTITY;
CREATE USER IF NOT EXISTS SRG_USER_6
    PASSWORD = 'TestPass123!'
    DEFAULT_ROLE = SRG_FINANCE_DDL;

GRANT ROLE SRG_SALES_IDENTITY TO USER SRG_USER_1;
GRANT ROLE SRG_FINANCE_IDENTITY TO USER SRG_USER_2;
GRANT ROLE SRG_READONLY_IDENTITY TO USER SRG_USER_3;
GRANT ROLE SRG_PARTIAL_IDENTITY TO USER SRG_USER_5;
GRANT ROLE SRG_FINANCE_DDL TO USER SRG_USER_6;

