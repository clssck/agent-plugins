GRANT USAGE ON SCHEMA AUTH_TEST_DB.AUTH_TEST_SCHEMA TO ROLE TEST_SCHEMA_ONLY_ROLE;

-- Role with SELECT on SALES_DATA only (schema 1)
CREATE ROLE IF NOT EXISTS TEST_SALES_READER_ROLE;
