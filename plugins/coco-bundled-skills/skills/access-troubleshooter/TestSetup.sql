CREATE DATABASE IF NOT EXISTS AUTH_TEST_DB;
CREATE SCHEMA IF NOT EXISTS AUTH_TEST_DB.AUTH_TEST_SCHEMA;
CREATE SCHEMA IF NOT EXISTS AUTH_TEST_DB.AUTH_TEST_SCHEMA_2;

CREATE TABLE IF NOT EXISTS AUTH_TEST_DB.AUTH_TEST_SCHEMA.SALES_DATA (
    id INT,
    amount DECIMAL(10,2),
    region VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS AUTH_TEST_DB.AUTH_TEST_SCHEMA.RESTRICTED_DATA (
    id INT,
    secret_value VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS AUTH_TEST_DB.AUTH_TEST_SCHEMA_2.ANALYTICS_DATA (
    id INT,
    metric VARCHAR(50),
    value DECIMAL(10,2)
);

-- View referencing two tables (for EXPLAIN_PRIVILEGES view-body-expansion test)
CREATE OR REPLACE VIEW AUTH_TEST_DB.AUTH_TEST_SCHEMA.EP_TEST_VIEW AS
    SELECT s.id, s.amount, r.secret_value
    FROM AUTH_TEST_DB.AUTH_TEST_SCHEMA.SALES_DATA s
    JOIN AUTH_TEST_DB.AUTH_TEST_SCHEMA.RESTRICTED_DATA r ON s.id = r.id;

-- Inner UDF referenced by the owner's-rights outer UDF
CREATE OR REPLACE FUNCTION AUTH_TEST_DB.AUTH_TEST_SCHEMA.EP_INNER_UDF()
    RETURNS VARCHAR
    LANGUAGE SQL
    AS 'SELECT secret_value FROM AUTH_TEST_DB.AUTH_TEST_SCHEMA.RESTRICTED_DATA LIMIT 1';

-- Owner's-rights UDF: body should NOT be expanded by EXPLAIN_PRIVILEGES
-- (SQL UDFs are owner's-rights by default; EXECUTE AS OWNER is procedure-only syntax)
CREATE OR REPLACE FUNCTION AUTH_TEST_DB.AUTH_TEST_SCHEMA.EP_OUTER_UDF()
    RETURNS VARCHAR
    LANGUAGE SQL
    AS 'SELECT AUTH_TEST_DB.AUTH_TEST_SCHEMA.EP_INNER_UDF()';

