GRANT USAGE ON DATABASE AUTH_TEST_DB TO ROLE TEST_FULL_ACCESS_ROLE;
GRANT USAGE ON SCHEMA AUTH_TEST_DB.AUTH_TEST_SCHEMA TO ROLE TEST_FULL_ACCESS_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA AUTH_TEST_DB.AUTH_TEST_SCHEMA TO ROLE TEST_FULL_ACCESS_ROLE;

-- Role with CREATE TABLE privilege on schema 1 (not granted to end user by default)
CREATE ROLE IF NOT EXISTS TEST_CREATOR_ROLE;
GRANT USAGE ON DATABASE AUTH_TEST_DB TO ROLE TEST_CREATOR_ROLE;
GRANT USAGE ON SCHEMA AUTH_TEST_DB.AUTH_TEST_SCHEMA TO ROLE TEST_CREATOR_ROLE;
GRANT CREATE TABLE ON SCHEMA AUTH_TEST_DB.AUTH_TEST_SCHEMA TO ROLE TEST_CREATOR_ROLE;

-- Role with access to schema 2 only (for cross-schema testing)
CREATE ROLE IF NOT EXISTS TEST_SCHEMA2_READER_ROLE;
GRANT USAGE ON DATABASE AUTH_TEST_DB TO ROLE TEST_SCHEMA2_READER_ROLE;
GRANT USAGE ON SCHEMA AUTH_TEST_DB.AUTH_TEST_SCHEMA_2 TO ROLE TEST_SCHEMA2_READER_ROLE;
