GRANT USAGE ON DATABASE AUTH_TEST_DB TO ROLE TEST_SCHEMA_CREATOR_ROLE;
GRANT CREATE SCHEMA ON DATABASE AUTH_TEST_DB TO ROLE TEST_SCHEMA_CREATOR_ROLE;

-- Partial EP role: USAGE on DB + SCHEMA but no MONITOR (for missing_only partial test)
